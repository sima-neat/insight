// One 64x48 frame each, captured from the board's payloader settings:
//
//	gst-launch-1.0 videotestsrc num-buffers=1 ! video/x-raw,width=64,height=48,format=I420 \
//	  ! jpegenc quality=50 ! rtpjpegpay mtu=300 ! udpsink host=127.0.0.1 port=<capture>
//
// with format=Y42B for the 4:2:2 fixture, one datagram per slice element. The
// pixel hashes are SHA-256 over the Y, Cb and Cr planes image/jpeg decodes from
// jpegenc's own output for the same frame (a tee before rtpjpegpay).
const (
	fixtureI420PixelHash = "3b71ea14bbd8a48296a6f6a262b473d0369321c85af1f15236cbbc25616ce81a"
	fixtureY42BPixelHash = "6c82a1c6fefca37dd51a28c9ada7964c5626cbeb0dad874ea7c74b08ee6d675d"
)

func TestAssembleJPEGRebuildsTheEncodedImage(t *testing.T) {
	for _, tt := range []struct {
		name      string
		packets   [][]byte
		jpegType  uint8
		pixelHash string
	}{
		{"type 1 (4:2:0)", fixtureI420, 1, fixtureI420PixelHash},
		{"type 0 (4:2:2)", fixtureY42B, 0, fixtureY42BPixelHash},
	} {
		t.Run(tt.name, func(t *testing.T) {
			if got := mustJPEGHeader(t, tt.packets[0]); got.typ != tt.jpegType || got.q != 255 {
				t.Fatalf("fixture is not type %d with in-band tables: %#v", tt.jpegType, got)
			}
			frame, err := assembleJPEG(tt.packets)
			if err != nil {
				t.Fatalf("assemble: %v", err)
			}
			if got := decodedPixelHash(t, frame); got != tt.pixelHash {
				t.Fatalf("decoded pixels differ from the encoder's image: %s", got)
			}
		})
	}
}

func TestAssembleJPEGDerivesTablesFromQ(t *testing.T) {
	inBand, err := assembleJPEG(fixtureI420)
	if err != nil {
		t.Fatal(err)
	}
	// jpegenc quality=50 sends the unscaled Annex K tables, which is what Q=50
	// must derive, so dropping them for Q=50 has to rebuild the same image.
	derived, err := assembleJPEG(withJPEGQ(t, fixtureI420, 50))
	if err != nil {
		t.Fatalf("assemble Q=50: %v", err)
	}
	if !bytes.Equal(derived, inBand) {
		t.Fatal("Q=50 tables differ from the unscaled tables sent in-band")
	}
	for _, q := range []uint8{1, 10, 99} {
		frame, err := assembleJPEG(withJPEGQ(t, fixtureI420, q))
		if err != nil {
			t.Fatalf("assemble Q=%d: %v", q, err)
		}
		decodedPixelHash(t, frame)
	}
	// Q=10 scales by 5000/10 = 500%: the luma DC entry 16 becomes 80.
	frame, _ := assembleJPEG(withJPEGQ(t, fixtureI420, 10))
	if dqt := bytes.Index(frame, []byte{0xff, 0xdb, 0, 67, 0}); dqt < 0 || frame[dqt+5] != 80 {
		t.Fatalf("Q=10 luma DC quantizer is not 80: %x", frame[:32])
	}
}

func TestAssembleJPEGEmitsRestartInterval(t *testing.T) {
	packets := withRestartHeader(t, fixtureI420, 0x0004ffff)
	frame, err := assembleJPEG(packets)
	if err != nil {
		t.Fatalf("assemble: %v", err)
	}
	dri := bytes.Index(frame, []byte{0xff, 0xdd, 0, 4, 0, 4})
	if dri < 0 || dri > bytes.Index(frame, []byte{0xff, 0xc0}) {
		t.Fatal("restart interval not emitted as DRI before SOF0")
	}

	if _, err := assembleJPEG(withRestartHeader(t, fixtureI420, 0x0000ffff)); err == nil {
		t.Fatal("accepted a zero restart interval")
	}
	changed := append([][]byte(nil), packets...)
	changed[1] = rewriteJPEGPayload(t, changed[1], func(payload []byte) []byte {
		payload[9] = 8
		return payload
	})
	if _, err := assembleJPEG(changed); err == nil {
		t.Fatal("accepted a restart interval that changed within a frame")
	}
	// Senders that align packets to restart intervals vary F, L and the count.
	aligned := append([][]byte(nil), packets...)
	aligned[1] = rewriteJPEGPayload(t, aligned[1], func(payload []byte) []byte {
		payload[10], payload[11] = 0x80, 0x01
		return payload
	})
	if _, err := assembleJPEG(aligned); err != nil {
		t.Fatalf("rejected per-packet restart flags and count: %v", err)
	}
}

func TestAssembleJPEGRejectsUnusableFrames(t *testing.T) {
	setByte := func(index int, value byte) func([]byte) []byte {
		return func(payload []byte) []byte {
			payload[index] = value
			return payload
		}
	}
	oversized := rewriteJPEGPayload(t, fixtureI420[len(fixtureI420)-1], func(payload []byte) []byte {
		return append(payload, make([]byte, maxJPEGFrameBytes)...)
	})
	for _, tt := range []struct {
		name    string
		packets [][]byte
		want    string
	}{
		{"offset gap", [][]byte{fixtureI420[0], fixtureI420[2]}, "fragment offset"},
		{"missing first fragment", fixtureI420[1:], "first fragment"},
		{"Q=0", withJPEGQ(t, fixtureI420, 0), "reserved"},
		{"Q=100", withJPEGQ(t, fixtureI420, 100), "reserved"},
		{"type 2", rewriteEach(t, fixtureI420, setByte(4, 2)), "type 2"},
		{"interlaced", rewriteEach(t, fixtureI420, setByte(0, 1)), "interlaced"},
		{"size change", [][]byte{fixtureI420[0], rewriteJPEGPayload(t, fixtureI420[1], setByte(6, 4)), fixtureI420[2]}, "changed"},
		{"out-of-band tables", [][]byte{rewriteJPEGPayload(t, fixtureI420[0], func(payload []byte) []byte {
			payload[10], payload[11] = 0, 0
			return payload
		})}, "out of band"},
		{"oversize", append(append([][]byte(nil), fixtureI420[:2]...), oversized), "exceeds"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			if _, err := assembleJPEG(tt.packets); err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("expected an error containing %q, got %v", tt.want, err)
			}
		})
	}
}

func mustJPEGHeader(t *testing.T, raw []byte) jpegMainHeader {
	t.Helper()
	var pkt rtp.Packet
	if err := pkt.Unmarshal(raw); err != nil {
		t.Fatal(err)
	}
	header, _, err := parseJPEGPayload(pkt.Payload)
	if err != nil {
		t.Fatal(err)
	}
	return header
}

func decodedPixelHash(t *testing.T, frame []byte) string {
	t.Helper()
	img, err := jpeg.Decode(bytes.NewReader(frame))
	if err != nil {
		t.Fatalf("decode rebuilt JPEG: %v", err)
	}
	if size := img.Bounds().Size(); size != image.Pt(64, 48) {
		t.Fatalf("decoded %v, expected 64x48", size)
	}
	planes := img.(*image.YCbCr)
	sum := sha256.Sum256(append(append(append([]byte(nil), planes.Y...), planes.Cb...), planes.Cr...))
	return hex.EncodeToString(sum[:])
}

func rewriteJPEGPayload(t *testing.T, raw []byte, rewrite func([]byte) []byte) []byte {
	t.Helper()
	var pkt rtp.Packet
	if err := pkt.Unmarshal(raw); err != nil {
		t.Fatal(err)
	}
	pkt.Payload = rewrite(append([]byte(nil), pkt.Payload...))
	out, err := pkt.Marshal()
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func rewriteEach(t *testing.T, packets [][]byte, rewrite func([]byte) []byte) [][]byte {
	t.Helper()
	out := make([][]byte, len(packets))
	for i, raw := range packets {
		out[i] = rewriteJPEGPayload(t, raw, rewrite)
	}
	return out
}

// withJPEGQ resends an in-band-table fixture with a table-less Q.
func withJPEGQ(t *testing.T, packets [][]byte, q uint8) [][]byte {
	t.Helper()
	return rewriteEach(t, packets, func(payload []byte) []byte {
		if payload[5] >= 128 && payload[1]|payload[2]|payload[3] == 0 {
			length := int(payload[10])<<8 | int(payload[11])
			payload = append(payload[:8], payload[12+length:]...)
		}
		payload[5] = q
		return payload
	})
}

// withRestartHeader turns a type 0/1 fixture into type 64/65 with the given
// restart header (interval << 16 | F | L | count).
func withRestartHeader(t *testing.T, packets [][]byte, header uint32) [][]byte {
	t.Helper()
	return rewriteEach(t, packets, func(payload []byte) []byte {
		restart := []byte{byte(header >> 24), byte(header >> 16), byte(header >> 8), byte(header)}
		out := append(append(append([]byte(nil), payload[:8]...), restart...), payload[8:]...)
		out[4] |= 64
		return out
	})
}

